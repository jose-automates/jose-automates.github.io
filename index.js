// Letters (any language, with accents) separated by single spaces or hyphens
const NAME_RE  = /^[\p{L}\p{M}]+(?:[ -][\p{L}\p{M}]+)*$/u;
// local@domain.tld: no leading/trailing/double dots, TLD of 2+ letters
const EMAIL_RE = /^[A-Za-z0-9](?:[A-Za-z0-9._%+-]{0,62}[A-Za-z0-9])?@(?:[A-Za-z0-9](?:[A-Za-z0-9-]{0,61}[A-Za-z0-9])?\.)+[A-Za-z]{2,24}$/;
// Anything that looks like code (HTML, JS, PHP, templates, SQL, shell). Plain links still pass.
const CODE_PATTERNS = [
  /[<>{}`\\]/,                                                          // tags, code blocks, template strings, escapes
  /\b(?:javascript|vbscript)\s*:/i,                                     // script URLs
  /\bdata\s*:\s*[a-z]+\/[a-z0-9.+-]+/i,                                 // data: URIs
  /\bon(?:click|load|error|mouse\w*|focus|blur|key\w*|submit|change|input)\s*=/i, // inline event handlers
  /\$\(|\$\w+\s*=|=>|&&|\|\|/,                                          // jQuery, shell/PHP vars, arrows, logic ops
  /\b(?:function|def)\s+\w+\s*\(/i,                                     // function definitions
  /\b(?:var|let|const)\s+\w+\s*=/,                                      // JS variable declarations
  /\b(?:eval|exec|alert|prompt|require|setTimeout|setInterval|system|passthru|shell_exec)\s*\(/i,
  /\b(?:document|window)\.(?:cookie|location|write|body|getElementById|querySelector)|\bconsole\.\w+\(|\bprocess\.env\b/i, // browser / Node objects
  /\w+\((?!s\))[^()]*\)\s*;/,                                           // statement calls like foo(bar);
  // SQL statements (written so plain English like "select the best from" still passes)
  /\bselect\s+(?:\*|[\w.]+(?:\s*,\s*[\w.]+)+|\w+\.\w+)\s+from\b|\bselect\s+\w+\s+from\s+\w+\s+where\b/i,
  /\binsert\s+into\s+\w+\s*(?:\(|values\b)|\bupdate\s+\w+\s+set\s+\w+\s*=|\bdelete\s+from\s+\w+\s*(?:;|where\b)/i,
  /\b(?:drop\s+(?:table|database)|union\s+(?:all\s+)?select|alter\s+table|truncate\s+table)\b/i,
  /['"]\s*(?:or|and)\s+['"]?\w+['"]?\s*=\s*['"]?\w+/i,                    // SQL injection like ' OR 1=1
  /[;'"]\s*--/,                                                         // SQL comments after a statement
  /\bsudo\s|\brm\s+-rf\b|\bchmod\s+\d|\b(?:curl|wget)\s+(?:-|https?:)/i  // shell commands
];

const form = document.getElementById('contactForm');
const fields = {
  name:    form.elements.name,
  email:   form.elements.email,
  message: form.elements.message
};

function cleanName(v)  { return v.trim().replace(/\s+/g, ' '); }
function cleanEmail(v) { return v.trim(); }
function cleanMsg(v)   { return v.trim(); }

// Each returns the i18n key of the error, or '' when the value is valid
function checkName(v) {
  v = cleanName(v);
  if (!v) return 'err_name_required';
  if (v.length < 2 || v.length > 60) return 'err_name_length';
  if (!NAME_RE.test(v)) return 'err_name_invalid';
  return '';
}
function checkEmail(v) {
  v = cleanEmail(v);
  if (!v) return 'err_email_required';
  if (v.length > 254 || !EMAIL_RE.test(v) || v.includes('..')) return 'err_email_invalid';
  return '';
}
function checkMessage(v) {
  v = cleanMsg(v);
  if (!v) return 'err_msg_required';
  if (v.length < 10 || v.length > 2000) return 'err_msg_length';
  if (CODE_PATTERNS.some(re => re.test(v))) return 'err_msg_code';
  return '';
}
const checks = { name: checkName, email: checkEmail, message: checkMessage };

function showError(key, errKey) {
  const input = fields[key];
  const box = document.getElementById('err-' + key);
  if (errKey) {
    input.setAttribute('aria-invalid', 'true');
    box.dataset.err = errKey;
    box.textContent = i18n[currentLang][errKey];
  } else {
    input.removeAttribute('aria-invalid');
    delete box.dataset.err;
    box.textContent = '';
  }
  return !errKey;
}
function validateField(key) { return showError(key, checks[key](fields[key].value)); }

Object.keys(fields).forEach(key => {
  const input = fields[key];
  // check when the visitor leaves a field they typed in
  input.addEventListener('blur', () => { if (input.value.trim()) validateField(key); });
  // once a field shows an error, re-check as they fix it
  input.addEventListener('input', () => {
    if (input.getAttribute('aria-invalid') === 'true') validateField(key);
  });
});

/* ── POPUP MODAL (replaces the browser alert box everywhere) ── */
// Each popup type is a set of i18n keys, so it re-translates if the language changes while open
const MODAL_TYPES = {
  errors:  { label: 'modal_label',      title: 'alert_fix',        text: null,              ok: 'modal_ok' },
  success: { label: 'modal_sent_label', title: 'modal_sent_title', text: 'modal_sent_text', ok: 'modal_sent_ok' },
  noEmail: { label: 'modal_sent_label', title: 'modal_sent_title', text: 'modal_noemail_text', ok: 'modal_sent_ok' },
  failed:  { label: 'modal_fail_label', title: 'modal_fail_title', text: 'modal_fail_text', ok: 'modal_ok' }
};
const modal = document.getElementById('siteModal');
let modalState = null;    // { type, fieldKeys, returnFocus, email }

function renderModal() {
  if (!modalState) return;
  const t = i18n[currentLang];
  const cfg = MODAL_TYPES[modalState.type];
  const good = modalState.type === 'success' || modalState.type === 'noEmail';
  modal.dataset.type = good ? 'success' : 'error';
  modal.querySelector('.modal-card').setAttribute('role', good ? 'dialog' : 'alertdialog');
  document.getElementById('modalLabel').textContent = t[cfg.label];
  document.getElementById('modalTitle').textContent = t[cfg.title];
  document.getElementById('modalText').textContent  = cfg.text ? t[cfg.text].replace('{email}', modalState.email || '') : '';
  document.getElementById('modalOk').textContent    = t[cfg.ok];
  // list of fields with problems (form errors only)
  document.getElementById('modalList').replaceChildren(...(modalState.fieldKeys || []).map(key => {
    const li = document.createElement('li');
    const label = document.createElement('strong');
    label.textContent = t['form_' + key];
    li.append(label, document.getElementById('err-' + key).textContent);
    return li;
  }));
}
function openModal(type, { fieldKeys = [], returnFocus = null, email = '' } = {}) {
  modalState = { type, fieldKeys, returnFocus, email };
  renderModal();
  modal.hidden = false;
  document.body.classList.add('modal-open');
  document.getElementById('modalOk').focus();
}
function closeModal() {
  if (modal.hidden) return;
  const back = modalState && modalState.returnFocus;
  modal.hidden = true;
  modalState = null;
  document.body.classList.remove('modal-open');
  if (back) back.focus();
}
modal.querySelectorAll('[data-close]').forEach(el => el.addEventListener('click', closeModal));
document.addEventListener('keydown', e => {
  if (modal.hidden) return;
  if (e.key === 'Escape') closeModal();
  // keep Tab inside the modal
  if (e.key === 'Tab') {
    const btns = [...modal.querySelectorAll('button')];
    const i = btns.indexOf(document.activeElement);
    e.preventDefault();
    btns[(i + (e.shiftKey ? -1 : 1) + btns.length) % btns.length].focus();
  }
});

/* ── CONTACT FORM (Formspree) ── */
// While a message is on its way, every other submit (double click, Enter key, etc.) is ignored
let isSending = false;
function setSending(on) {
  isSending = on;
  const btn = form.querySelector('button[type="submit"]');
  btn.disabled = on;
  btn.textContent = i18n[currentLang][on ? 'form_sending' : 'form_send'];
  form.classList.toggle('is-sending', on);
  form.setAttribute('aria-busy', on ? 'true' : 'false');
  Object.values(fields).forEach(f => { f.readOnly = on; });
}

form.addEventListener('submit', async e => {
  e.preventDefault();
  if (isSending) return;
  const keys = Object.keys(fields);
  const results = keys.map(validateField);
  if (results.includes(false)) {
    const bad = keys.filter((key, i) => !results[i]);
    openModal('errors', { fieldKeys: bad, returnFocus: fields[bad[0]] });
    return;
  }
  // send the cleaned values
  fields.name.value    = cleanName(fields.name.value);
  fields.email.value   = cleanEmail(fields.email.value);
  fields.message.value = cleanMsg(fields.message.value);

  setSending(true);
  const sentTo = fields.email.value;
  let status = 0;
  let data = {};
  // n8n answers after the email is sent (AI + Gmail take a few seconds); give up after 30 s
  const ctrl = new AbortController();
  const timer = setTimeout(() => ctrl.abort(), 30000);
  try {
    // CORS-safe "simple" request: POST + URL-encoded body + only the Accept header,
    // so the browser sends it straight away with no preflight (OPTIONS) request.
    // n8n only returns the CORS header to jose-automates.github.io (and the local preview).
    const res = await fetch(form.action, {
      method: 'POST',
      mode: 'cors',
      credentials: 'omit',
      body: new URLSearchParams(new FormData(form)),
      headers: { Accept: 'application/json' },
      signal: ctrl.signal
    });
    status = res.status;
    data = await res.json().catch(() => ({}));
  } catch {
    status = 0;   // offline, timeout or blocked: same popup as a failed send
  } finally {
    clearTimeout(timer);
    setSending(false);
  }

  if (status >= 200 && status < 300 && data.ok !== false) {
    form.reset();   // clear the fields for the next message
    openModal(data.emailSent === false ? 'noEmail' : 'success', { email: sentTo });
    return;
  }
  // the server rejected a field (it re-checks with the same rules)
  const bad = serverErrorsToFields(data.errors);
  if (status === 400 && bad.length) {
    openModal('errors', { fieldKeys: bad, returnFocus: fields[bad[0]] });
    return;
  }
  openModal('failed');   // keep what they typed so they can retry
});

// Server codes look like "name_invalid" / "message_code"; map them to our field errors
function serverErrorsToFields(codes) {
  const map = {
    name_required: ['name', 'err_name_required'],
    name_length: ['name', 'err_name_length'],
    name_invalid: ['name', 'err_name_invalid'],
    email_required: ['email', 'err_email_required'],
    email_invalid: ['email', 'err_email_invalid'],
    message_required: ['message', 'err_msg_required'],
    message_length: ['message', 'err_msg_length'],
    message_code: ['message', 'err_msg_code']
  };
  const keys = [];
  (Array.isArray(codes) ? codes : []).forEach(code => {
    const hit = map[code];
    if (hit && !keys.includes(hit[0])) {
      showError(hit[0], hit[1]);
      keys.push(hit[0]);
    }
  });
  return keys;
}

