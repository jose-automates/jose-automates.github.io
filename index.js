/* ── LANGUAGE DETECTION ── */
function detectLang() {
  const saved = localStorage.getItem('jag_lang');
  if (saved) return saved;
  const browser = navigator.language || navigator.userLanguage || 'en';
  return browser.toLowerCase().startsWith('es') ? 'es' : 'en';
}
 
let currentLang = detectLang();
 
function applyLang(lang) {
  currentLang = lang;
  localStorage.setItem('jag_lang', lang);
  document.documentElement.lang = lang;
 
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.dataset.i18n;
    if (i18n[lang][key] !== undefined) el.textContent = i18n[lang][key];
  });
  document.querySelectorAll('[data-i18n-html]').forEach(el => {
    const key = el.dataset.i18nHtml;
    if (i18n[lang][key] !== undefined) el.innerHTML = i18n[lang][key];
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.dataset.i18nPlaceholder;
    if (i18n[lang][key] !== undefined) el.placeholder = i18n[lang][key];
  });
 
  document.querySelectorAll('[data-i18n-aria]').forEach(el => {
    const key = el.dataset.i18nAria;
    if (i18n[lang][key] !== undefined) el.setAttribute('aria-label', i18n[lang][key]);
  });
  // keep "Sending..." on the button if the language changes mid-send
  const sendingBtn = document.querySelector('#contactForm.is-sending button[type="submit"]');
  if (sendingBtn) sendingBtn.textContent = i18n[lang].form_sending;
  document.querySelectorAll('.field-error[data-err]').forEach(el => {
    el.textContent = i18n[lang][el.dataset.err];
  });
  if (typeof renderModal === 'function') renderModal();

  const toggle = document.getElementById('langToggle');
  toggle.textContent = lang === 'en' ? 'ES' : 'EN';
  syncSkillsWidth();
  syncColumnWidths();
}

/* ── SKILLS GRID = WIDTH OF HERO TITLE (desktop) ── */
function syncSkillsWidth() {
  const title = document.querySelector('.hero-title');
  const skills = document.querySelector('.hero-skills');
  const range = document.createRange();
  range.selectNodeContents(title);
  const left = title.getBoundingClientRect().left;
  const right = Math.max(...[...range.getClientRects()].map(r => r.right));
  skills.style.setProperty('--title-w', Math.ceil(right - left) + 'px');
}
window.addEventListener('resize', syncSkillsWidth);
document.fonts.ready.then(syncSkillsWidth);

/* ── ABOUT / CONTACT PARAGRAPHS ≤ WIDTH OF THEIR TITLE (tablet) ── */
function syncColumnWidths() {
  ['#about .about-text', '#contact .contact-info'].forEach(sel => {
    const col = document.querySelector(sel);
    const range = document.createRange();
    range.selectNodeContents(col.querySelector('.section-title'));
    const rects = [...range.getClientRects()];
    const width = Math.max(...rects.map(r => r.right)) - Math.min(...rects.map(r => r.left));
    col.style.setProperty('--col-title-w', Math.floor(width) + 'px');
  });
}
window.addEventListener('resize', syncColumnWidths);
document.fonts.ready.then(syncColumnWidths);
 
